const H = require("../history.js");
let failed = 0;
const check = (n, ok) => { console.log((ok ? "OK    " : "ОШИБКА ") + n); if (!ok) failed++; };
const t = (date, amount, cat) => ({ date, amount, cat: cat || "Прочее" });

// Октябрь целиком
const oct = H.summarize([t("2026-10-02", -100, "Продукты"), t("2026-10-05", -50), t("2026-10-20", -200), t("2026-10-31", -50)], { from: "2026-10-01", to: "2026-10-31" });
check("сводка: итог, дни, категории", oct["2026-10"].total === 400 && oct["2026-10"].days[2] === 100 && oct["2026-10"].cats["Продукты"] === 100);
check("сводка: покрытие полного месяца", oct["2026-10"].first === 1 && oct["2026-10"].last === 31);
check("в сводке нет описаний", !JSON.stringify(oct).match(/name|desc/));

// Ноябрь за 8 дней, выписка с 1 по 8
const nov = H.summarize([t("2026-11-02", -150), t("2026-11-04", -50), t("2026-11-08", -50)], { from: "2026-11-01", to: "2026-11-08" });
check("неполный месяц: покрытие 1–8", nov["2026-11"].first === 1 && nov["2026-11"].last === 8);
const c1 = H.compare("2026-11", nov["2026-11"], oct["2026-10"]);
check("за те же числа: 250 против 150 = +67%", c1 && c1.pct === 67 && !c1.full && c1.b === 8);

// Полный против полного
const dec = H.summarize([t("2026-11-10", -200), t("2026-11-30", -200), t("2026-12-01", -100), t("2026-12-31", -100)], { from: "2026-11-01", to: "2026-12-31" });
check("полный месяц против полного: ноябрь 400, декабрь 200 = -50%", H.compare("2026-12", dec["2026-12"], dec["2026-11"]).pct === -50);
check("полный против неполного: нет сравнения", H.compare("2026-12", dec["2026-12"], nov["2026-11"]) === null);
check("мало дней (меньше 5): нет сравнения", H.compare("2026-11", H.summarize([t("2026-11-02", -10)], { from: "2026-11-01", to: "2026-11-03" })["2026-11"], oct["2026-10"]) === null);
check("прошлый месяц начат позже нужного дня: нет сравнения", H.compare("2026-11", nov["2026-11"], H.summarize([t("2026-10-20", -10)], { from: "2026-10-15", to: "2026-10-31" })["2026-10"]) === null);
check("прошлый месяц пустой за эти числа: нет сравнения", H.compare("2026-11", nov["2026-11"], H.summarize([t("2026-10-20", -10)], { from: "2026-10-01", to: "2026-10-31" })["2026-10"]) === null);

// Слияние: берётся тот, где данных больше; равные: побеждает новый
const part = H.summarize([t("2026-10-02", -1)], { from: "2026-10-01", to: "2026-10-10" });
let st = H.merge({}, oct);
st = H.merge(st, part);
check("слияние: короткое не затирает полное", st["2026-10"].total === 400);
const again = H.summarize([t("2026-10-02", -999)], { from: "2026-10-01", to: "2026-10-31" });
check("слияние: равное покрытие заменяет", H.merge(st, again)["2026-10"].total === 999);
const many = {}; for (let i = 0; i < 30; i++) many[H.addMonths("2024-01", i)] = oct["2026-10"];
check("хранится не больше 24 месяцев", Object.keys(H.merge(many, {})).length === 24);
check("мусорный ключ не принимается", !("x" in H.merge({}, { x: oct["2026-10"] })));
check("пустой список: пустая сводка", Object.keys(H.summarize([], {})).length === 0);
// v4.65: возврат уменьшает траты месяца и категории, в минус не уводит
{
  const s = H.summarize([{ date: "2026-09-02", amount: -50, cat: "Продукты" }, { date: "2026-09-04", amount: 20, cat: "Продукты", refund: true },
    { date: "2026-09-05", amount: 100, cat: "Пополнения" }, { date: "2026-09-06", amount: 30, cat: "Кафе и рестораны", refund: true }], { from: "2026-09-01", to: "2026-09-30" });
  const m = s["2026-09"];
  check("возврат: траты месяца 50 − 20 − 30 = 0, поступление без отметки не учтено", m && m.total === 0);
  check("возврат: Продукты 30, кафе без покупок не в минусе", m && m.cats["Продукты"] === 30 && !("Кафе и рестораны" in m.cats));
}
process.exit(failed ? 1 : 0);
