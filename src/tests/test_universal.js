check("не число: слово и дата", Number.isNaN(U.num("Сумма")) && Number.isNaN(U.num("01.02.2026")));
check("дата: дд.мм.гггг, дд/мм/гг и гггг-мм-дд", U.dateOf("05.03.2026") === "2026-03-05" && U.dateOf("05/03/26") === "2026-03-05" && U.dateOf("2026-03-05 10:00") === "2026-03-05");
