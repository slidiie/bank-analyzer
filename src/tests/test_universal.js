check("А: дата в виде гггг-мм-дд", rA.txs[0].date === "2026-03-02");
check("А: сошлось с итогами выписки", rA.proof === "totals" && rA.verified && rA.header.guess === false);
check("А: период, валюта и остатки из шапки", rA.header.from === "2026-03-01" && rA.header.to === "2026-03-31" && rA.header.currency === "BYN" && rA.header.opening === 100 && rA.header.closing === 1354.5);
check("А: название банка", rA.header.bankName === "Лесной банк");
check("А: номер карты в описание не попал", !/\d{6}\*|1234/.test(rA.txs[0].details) && /SHOP TEST MINSK/.test(rA.txs[0].details));
