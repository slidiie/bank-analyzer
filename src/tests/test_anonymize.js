// Тест анонимайзера на выдуманных данных. Запуск из папки src:  node tests/test_anonymize.js
const A = require("../anonymize.js");
let bad = 0;
const ok = (c, m) => { console.log((c ? "OK    " : "FAIL  ") + m); if (!c) bad++; };
const B = A.BLOCK;
// Выдуманные значения собираются из кусков, чтобы проверка публикации не принимала их за настоящие
const iban = "BY00" + "TEST" + "3000" + "00000000" + "00000000";
const card = "4000 " + "0000 0000 " + "0002";
const mail = "te" + "st@exa" + "mple.com";
const phone = "+375 " + "29 000 " + "00 00";
const fio = "Тестов Тест Тестович";

const hid = t => A.maskParts(t).some(p => p.m);
ok(hid(iban), "IBAN скрывается");
ok(hid("Счёт " + iban + " BYN"), "IBAN внутри строки скрывается, остальное остаётся");
ok(A.maskParts("Счёт " + iban + " BYN").filter(p => !p.m).map(p => p.t).join("") === "Счёт  BYN", "вокруг IBAN текст не тронут");
ok(hid(card), "номер карты скрывается");
ok(hid("400000******0002") || hid("400000****"), "маска карты с началом номера скрывается");
ok(hid(mail), "почта скрывается");
ok(hid(phone), "телефон скрывается");
ok(hid(fio), "ФИО с отчеством скрывается");
ok(hid("Минск, ул. Тестовая, д. 1, кв. 2"), "адрес скрывается");
ok(hid("Договор 123456" + "7890123"), "длинный номер скрывается");
ok(!hid("1 234.56"), "сумма не скрывается");
ok(!hid("-1 234 567.89"), "большая сумма с пробелами не скрывается");
ok(!hid("07.11.2026 12:34"), "дата и время не скрываются");
ok(!hid("EVROOPT MINSK BY"), "название магазина не скрывается");
ok(!hid("MCC 5411"), "MCC не скрывается");

// v4.62: ФИО заглавными, фамилия с инициалами, маска карты с пробелами
const FAM = "ТЕС" + "ТОВ", NAM = "ТЕ" + "СТ";
ok(hid("ПЕРЕВОД " + FAM + " " + NAM + " " + NAM + "ОВИЧ"), "ФИО заглавными скрывается");
ok(A.maskParts("ПЕРЕВОД " + FAM + " " + NAM + " " + NAM + "ОВНА")[0].t === "ПЕРЕВОД ", "перед ФИО заглавными слово не тронуто");
ok(hid("Перевод Тес" + "тов Т.Т."), "фамилия с инициалами скрывается");
ok(hid(FAM + " Т. Т."), "фамилия заглавными с инициалами через пробел скрывается");
ok(hid("от Т.Т. Тес" + "тов"), "инициалы перед фамилией скрываются");
ok(hid("4000 00" + "** **** 0002"), "маска карты с пробелами скрывается");
ok(hid("4000 00" + "XX XXXX 0002"), "маска карты с X скрывается");
ok(!hid("ГОМЕЛЬ ТЭЦ ОПЛАТА ЖКХ"), "заглавные слова без отчества не скрываются");
ok(!hid("SHOP MINSK BY 07.11.2026"), "латинское название с датой не скрывается");

// Строки и подпись «Владелец:»
const items = [
  { x: 10, y: 700, vx: 10, vy: 100, text: "Владелец счёта:" },
  { x: 120, y: 700, vx: 120, vy: 100.4, text: "Тест Т. Т." },
  { x: 10, y: 680, vx: 10, vy: 120, text: "07.11.2026" },
  { x: 90, y: 680, vx: 90, vy: 120, text: "EVROOPT" },
  { x: 200, y: 680, vx: 200, vy: 120, text: "-12.50" }
];
const rows = A.groupRows(items);
ok(rows.length === 2, "элементы сгруппированы в 2 строки");
ok(A.isHidden(rows[0][1]), "значение после «Владелец счёта:» скрывается");
ok(!A.isHidden(rows[1][0]) && !A.isHidden(rows[1][1]) && !A.isHidden(rows[1][2]), "обычная строка операции не тронута");

// Ручное управление
const it = rows[1][1];
it.manual = true;
ok(A.effective(it) === B.repeat(7), "ручное скрытие заменяет буквы знаками, длина сохраняется");
it.manual = false;
ok(A.effective(it) === "EVROOPT", "ручное «показать» возвращает обычный текст");
ok(A.effective(rows[0][1]) === "Тест Т. Т.".replace(/\S/g, B), "автоскрытое значение заменено знаками");
rows[0][1].manual = false;
ok(A.effective(rows[0][1]) === "Тест Т. Т.".replace(/\S/g, B), "автоскрытое открыть нельзя, даже если manual=false");
rows[0][1].manual = null;
const forced = A.groupRows([{ x: 1, y: 1, vx: 1, vy: 1, text: iban }])[0][0];
forced.manual = false;
ok(A.effective(forced) === hideAll(iban) && A.isAutoHidden(forced), "IBAN нельзя открыть никак");
function hideAll(x) { return x.replace(/\S/g, B); }

// Образец: исходного текста скрытого нет нигде
const model = [[[A_item(iban), A_item("Сумма 10.00")]]];
function A_item(text) { return A.groupRows([{ x: 1, y: 1, vx: 1, vy: 1, text }])[0][0]; }
const sample = A.toSample(model, "pdf", { app: "test", consent: "ok" });
const json = JSON.stringify(sample);
ok(!json.includes(iban), "IBAN не попал в образец");
ok(json.includes("Сумма 10.00"), "обычный текст в образце есть");
ok(sample.pages.length === 1 && sample.pages[0].length === 2, "структура образца: страницы → элементы");
ok(sample.pages[0][0].vx === 1 && sample.pages[0][0].vy === 1, "позиции сохранены");
ok(!A.toPlainText(model).includes(iban), "текст для просмотра тоже без IBAN");

// CSV
const csv = "Дата;Описание;Сумма\n07.11.2026;Оплата " + card + ";-5.00\nВладелец;" + fio + ";\n";
const cm = A.fromCsvText(csv, 2);
ok(cm.length === 2, "CSV разбит на страницы по строкам");
const cs = A.toSample(cm, "csv", {});
const cjson = JSON.stringify(cs);
ok(!cjson.includes(card) && !cjson.includes(fio), "CSV: карта и ФИО не попали в образец");
ok(cs.csv.length === 3 && cs.csv[0] === "Дата;Описание;Сумма", "CSV: заголовок и число строк сохранены");
ok(A.stats(cm).hidden >= 2, "статистика считает скрытые фрагменты");

// ---- Проверка 13.11 (АУДИТ-безопасность.md, находка 7): что просачивалось в образец и зависание ----
{
  // Выдуманные значения собраны из кусков, чтобы проверка публикации не приняла их за настоящие
  const F = "Тес" + "тов", I = "Те" + "ст", FL = "TES" + "TOU", IL = "TE" + "ST";
  const eff = s => A.effective({ text: s, parts: A.maskParts(s), manual: null });
  const gone = (s, ...secrets) => secrets.every(x => !eff(s).includes(x));
  ok(gone("Перевод от " + F + " " + I, F), "имя без отчества после «от» скрывается");
  ok(gone("Перевод для " + F.toUpperCase() + " " + I.toUpperCase(), F.toUpperCase()), "имя заглавными после «для» скрывается");
  ok(gone("Перевод от " + I + " Т.", I + " Т"), "имя с одним инициалом скрывается");
  ok(gone("Клиент " + F + " " + I, F) && gone("Владелец счёта " + IL + " " + FL, FL), "имя после подписи без двоеточия скрывается (и латиницей)");
  ok(gone("Cardholder: " + IL + " " + FL, FL) && gone("Client name: " + IL + " " + FL, FL), "английские подписи: значение скрывается");
  ok(gone("Уладальнік: " + F + " " + I, F) && gone(F + " " + I + " Тэставіч", F), "белорусская подпись и белорусское отчество");
  ok(gone("Идентификационный номер 30" + "10190A0" + "01PB5", "01PB5") && gone("док. 30" + "10190A0" + "01PB5 выдан", "10190A0"), "личный номер скрывается");
  ok(gone("документ MP" + "0000" + "001 от 01.01.2020", "0000001"), "номер паспорта скрывается");
  ok(gone("тел. 8 (029) 000-" + "00-01", "00-01") && gone("тел. (29) 000-" + "00-01", "00-01"), "телефон со скобками скрывается");
  ok(gone("Дата рождения: 01.02.1990", "1990") && gone("рожд. 01.02.1990", "1990"), "дата рождения скрывается");
  ok(gone("пр. Тестовый, 10-25", "Тестовый") && gone("мкр. Тестово, 12-34", "Тестово") && gone("вул. Тэставая, д. 5", "Тэставая"), "адрес с «пр.», «мкр.», «вул.» скрывается");
  ok(gone("тест@" + "почта.бел", "тест@"), "почта кириллицей скрывается");
  ok(gone("Договор № 00" + "000012", "000012") && gone("номер счета 00" + "012, 02.11.2026", "00012"), "короткий номер после «№» и «номер счета» скрывается");
  ok(gone("Карта *0" + "002", "0002") && gone("Карта 4***********0" + "002", "0002"), "хвост номера карты скрывается");
  ok(gone("Кодовое слово: ромашка", "ромашка"), "кодовое слово скрывается");
  const rows = A.groupRows([{ text: "Владелец счёта:", x: 10, y: 100, vx: 10, vy: 100 }, { text: F + " " + I, x: 10, y: 88, vx: 10, vy: 112 }, { text: "Период:", x: 300, y: 88, vx: 300, vy: 112 }]);
  ok(A.isHidden(rows[1][0]) && !A.isHidden(rows[1][1]), "подпись в конце строки, значение строкой ниже: скрывается оно, а не сосед");
  // Лишнего не скрываем: по образцу потом пишется чтение нового банка
  ok(!hid("Оплата от 01.10.2026") && !hid("Перевод для оплаты услуг") && !hid("Клиент оплатил услуги"), "«от», «для», «клиент» без имени ничего не скрывают");
  ok(!hid("Покупка товара SHOP 1234 MINSK BY") && !hid("Остаток на счёте 1234,56 BYN") && !hid("Сумма 12345,00 счёт 12345,67"), "магазин и суммы не скрываются");
  ok(!hid("Пр. платежи") && !hid("опл. услуг связи") && !hid("Name of merchant: SHOP") && !hid("Дата операции: 01.10.2026"), "«пр.», «опл.», Name of merchant, дата операции не скрываются");
  // Зависание: до исправления строка из 300 000 букв без пробелов разбиралась больше минуты (шаблон почты)
  for (const s of ["a".repeat(300000), "А".repeat(300000), "a.".repeat(900), "А".repeat(1999), "Аа ".repeat(600), "от " + "Аа ".repeat(600), "1 ".repeat(990), "ул. " + "х".repeat(1900), "имя ".repeat(480) + ":"]) {
    const t = Date.now(); const p = A.maskParts(s);
    ok(Date.now() - t < 500 && p.map(x => x.t).join("") === s, "без зависания: " + s.slice(0, 6) + "… (" + s.length + " знаков)");
  }
  ok(A.maskParts("a".repeat(300000)).every(p => p.m), "кусок длиннее 2000 знаков скрывается целиком");
  // Очень большая страница: до исправления toSample падал («Maximum call stack size exceeded»)
  const bigPage = Array.from({ length: 150000 }, (_, i) => ({ text: "x", x: 1, y: i * 3, vx: 1, vy: i * 3 }));
  let sample = null; try { sample = A.toSample(A.fromPdfPages([bigPage]), "pdf", {}); } catch (e) { sample = null; }
  ok(!!sample && sample.pages[0].length === 150000, "страница из 150 000 строк: образец собирается");
}
console.log(bad ? `\nПровалено: ${bad}` : "\nВсе проверки пройдены.");
process.exit(bad ? 1 : 0);
