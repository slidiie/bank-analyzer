const C = require("../condrules.js");
let bad = 0; const check = (n, ok) => { if (!ok) { bad++; console.log("FAIL", n); } };
const tx = (d, a) => ({ details: d, amount: a });
check("пустое правило отброшено", C.clean({ t: "", c: "Еда" }) === null && C.clean({ t: "x", c: "" }) === null);
check("min больше max отброшено", C.clean({ t: "x", min: 10, max: 5, c: "Еда" }) === null);
check("текст нормализуется", C.clean({ t: "  ЕВРООПТ  Ё", c: "Еда" }).t === "евроопт е");
check("только сумма допустима", C.clean({ min: "5,5", c: "Еда" }).min === 5.5);
check("совпадение по тексту", C.matches(C.clean({ t: "евроопт", c: "Еда" }), tx("EVROOPT Минск".replace("EVROOPT", "ЕвроОпт"), -10)));
check("несовпадение текста", !C.matches(C.clean({ t: "евроопт", c: "Еда" }), tx("Гиппо", -10)));
check("граница суммы включена", C.matches(C.clean({ t: "а", min: 10, max: 20, c: "Е" }), tx("а", -20)) && !C.matches(C.clean({ t: "а", min: 10, max: 20, c: "Е" }), tx("а", -20.01)));
check("только расходы", !C.matches(C.clean({ t: "а", kind: "expense", c: "Е" }), tx("а", 5)));
check("только поступления", C.matches(C.clean({ t: "а", kind: "income", c: "Е" }), tx("а", 5)));
check("неизвестный вид -> any", C.clean({ t: "а", kind: "хм", c: "Е" }).kind === "any");
check("первое подходящее по порядку", C.firstMatch([C.clean({ t: "а", c: "1" }), C.clean({ t: "а", c: "2" })], tx("а", -1)).c === "1");
check("нет совпадений -> null", C.firstMatch([], tx("а", -1)) === null);
check("лимит правил", C.cleanList(Array.from({ length: 80 }, (_, i) => ({ t: "т" + i, c: "К" }))).length === C.MAX_RULES);
check("не массив -> пусто", C.cleanList({}).length === 0);
check("описание", C.describe(C.clean({ t: "а", min: 1, kind: "expense", c: "К" })).includes("только расходы"));
console.log(bad ? "ОШИБКА" : "Все проверки пройдены");
process.exit(bad ? 1 : 0);
