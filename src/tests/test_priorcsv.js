// Тест CSV-выписки Приорбанка на ВЫДУМАННЫХ данных (имена, IBAN, номера и суммы тестовые).
// Запуск из папки проекта:  node tests/test_priorcsv.js

const C = require("../priorcsv.js");
const Banks = require("../banks.js");
const Cat = require("../categories.js");
const Merge = require("../merge.js");

let failed = 0;
const check = (name, ok) => { if (!ok) failed++; console.log((ok ? "OK    " : "FAIL  ") + name); };

// Расходы: 40,00 − 0,80 (Money-back) = 39,20; 62,00 (20 USD); 15,00; 8,50; 5,00; 4,00 → 133,70. Приход: 1 000,50 + 50,00.
const CSV = [
  "Выписка по контракту",
  "Период выписки:;01.10.2026-31.10.2026;",
  "Номер контракта:;......0001 Валюта контракта BYN;",
  "Карта:;........0002 BELKART;",
  "ФИО:; Тестов Тест;",
  "Адрес:;Тестовый адрес 1;",
  "",
  "Валюта счета: ;BYN;",
  "Начальный баланс: ;100,00",
  "",
  "Операции по ........0001",
  "Дата транзакции;Операция;Сумма;Валюта;Дата операции по счету;Комиссия/Money-back;Обороты по счету;Цифровая карта;Категория операции;",
  "21.10.2026 00:00:00;Поступление на контракт клиента 123456-12345-123456  ;1 000,50;BYN;21.10.2026;0,00;1 000,50;;;",
  "20.10.2026 10:00:00;Зачисление денежных средств   Онлайн пополнение счета IBAN: BY00TEST00000000000000000000  ;50,00;BYN;20.10.2026;0,00;50,00;;;",
  "",
  "Операции по ........0002",
  "Дата транзакции;Операция;Сумма;Валюта;Дата операции по счету;Комиссия/Money-back;Обороты по счету;Цифровая карта;Категория операции;",
  '22.10.2026 12:00:00;Retail BLR MINSK SHOP "EVROOPT"  ;-40,00;BYN;23.10.2026;0,80;-39,20;;Магазины продуктовые;',
  "23.10.2026 18:36:09;Retail HKG Hong Kong OTO*Telegram  ;-20,00;USD;26.10.2026;0,00;-62,00;;Цифровые товары;",
  "24.10.2026 09:00:00;ATM BLR MINSK VBBY  ;-15,00;BYN;24.10.2026;0,00;-15,00;;Снятие наличных;",
  "25.10.2026 09:00:00;Retail BLR MINSK PT KOFEJNYA N 4B  ;-8,50;BYN;26.10.2026;0,00;-8,50;;Ресторация / бары / кафе;",
  "26.10.2026 09:00:00;Retail BLR MINSK UNKNOWN PLACE  ;-5,00;BYN;27.10.2026;0,00;-5,00;;Магазины хозтоваров;",
  "27.10.2026 09:00:00;Retail BLR MINSK MOBILE BANK  ;-4,00;BYN;28.10.2026;0,00;-4,00;;Денежные переводы;",
  "28.10.2026 09:00:00;Нулевая операция  ;0,00;BYN;28.10.2026;0,00;0,00;;;",
  "",
  "Всего по контракту;Зачислено;Списано;Комиссия/Money-back;Изменение баланса;",
  ";1 050,50;134,50;0,80;916,80;",
  "",
  "Всего в данной валюте;Зачислено;Списано;Комиссия/Money-back;Конечный баланс;",
  ";1 050,50;134,50;0,80;1 016,80;",
  "",
  "Заблокированные суммы по ........0002",
  "Дата транзакции;Транзакция;Сумма транзакции;Валюта;Сумма блокировки;Валюта;Цифровая карта;Категория операции;",
  "29.10.2026 11:39:38;Retail BLR MINSK HOLD SHOP;4,47;BYN;4,47;BYN;;Ресторация / бары / кафе;",
  "",
].join("\r\n");

check("формат определяется", C.detect(CSV) && !C.detect("a;b;c\n1;2;3") && !C.detect(""));
const res = Banks.parseCsv(CSV);
check("банк Приорбанк", res && res.bank.id === "prior");
const h = res.header, t = res.txs;
check("шапка: период, валюта, остаток, итоги", h.from === "2026-10-01" && h.to === "2026-10-31" && h.currency === "BYN" && h.opening === 100 && h.income === 1050.5 && h.gross === 134.5 && h.moneyBack === 0.8 && h.closing === 1016.8);
check("расход в итогах за вычетом Money-back: 134,50 − 0,80 = 133,70", h.expense === 133.7);
check("ФИО, адрес, IBAN и номера нигде не сохранены", !JSON.stringify(res).match(/Тестов|Тестовый адрес|BY00TEST|123456-12345|0002/));
check("операций 8: нулевая пропущена, заблокированные суммы не читаются", t.length === 8 && !t.some(x => /HOLD/.test(x.details)));
check("числа с пробелом тысяч и запятой", t[0].amount === 1000.5);
check("сумма из «Обороты по счету» (за вычетом Money-back)", t[2].amount === -39.2);
check("кавычки в названии разобраны", /SHOP "EVROOPT"/.test(t[2].details));
check("валютная операция: сумма в BYN, исходная в описании", t[3].amount === -62 && t[3].origAmount === 20 && /20\.00 USD/.test(t[3].details));
check("дата и время", t[3].date === "2026-10-23" && t[3].time === "18:36:09" && t[3].regDate === "2026-10-26");
check("снятие наличных: метка и категория", /^Выдача наличных/.test(t[4].details) && Cat.categorize(t[4]) === "Наличные");
check("категория банка сохраняется", t[2].bankCat === "Магазины продуктовые" && t[0].bankCat === undefined);
check("название места сильнее категории банка (EVROOPT → Продукты)", Cat.categorize(t[2]) === "Продукты");
check("кофейня → Кафе и рестораны", Cat.categorize(t[5]) === "Кафе и рестораны");
const r6 = Cat.resolve(t[6]);
check("неизвестное место берёт категорию банка и объясняет причину", r6[0] === "Товары для дома" && /категория банка/.test(r6[1]));
check("«Цифровые товары» и «Денежные переводы» банка не навязываются", Cat.resolve({ ...t[3], details: "Retail HKG SOMETHING" })[0] === null && Cat.categorize(t[7]) === null);
check("«Mobile bank» попадает в корзину интернет-банка", Cat.bucket(t[7]) === "Платежи через интернет-банк");

const v = res.bank.validate(t, h);
check("сверка итогов сходится", v.ok === true && v.income === 1050.5 && v.expense === 133.7);
check("при потере операции сверка не сходится", res.bank.validate(t.slice(1), h).ok === false);
check("баланс сходится: 100 + операции = конечный", Math.round((100 + t.reduce((a, x) => a + x.amount, 0)) * 100) / 100 === 1016.8);

check("кодировка windows-1251 читается", C.decode(Buffer.from("c2fbefe8f1eae020efee20eaeeedf2f0e0eaf2f3", "hex")) === "Выписка по контракту");
check("кодировка UTF-8 (с BOM) тоже", C.decode(Buffer.from("﻿Выписка", "utf8")) === "Выписка");
check("разделитель внутри кавычек", JSON.stringify(C.splitRow('a;"b;c";d')) === '["a","b;c","d"]');

// Повреждённая строка не ломает разбор
const bad = CSV.replace("-15,00;BYN;24.10.2026;0,00;-15,00", "-15,00;BYN;24.10.2026;0,00;abc");
const rb = Banks.parseCsv(bad);
check("повреждённая сумма считается в «не удалось разобрать»", rb.header.broken === 1 && rb.txs.length === 7 && rb.bank.validate(rb.txs, rb.header).ok === false);

// Две валюты в одном файле: сайт знает, что счетов несколько (аудит 13.11, А5)
check("одна валюта: один счёт", res.header.accounts === 1);
const two = CSV.replace("Заблокированные суммы", "Всего в данной валюте;Зачислено;Списано;Комиссия/Money-back;Конечный баланс;\r\n;0,00;0,00;0,00;0,00;\r\n\r\nЗаблокированные суммы");
check("две строки «Всего в данной валюте»: счетов два", Banks.parseCsv(two).header.accounts === 2);

// Тот же период из CSV и из PDF не задваивается: идентификатор операции совпадает
const state = Merge.newState();
const a1 = Merge.addStatement(state, { ...res, check: null });
const a2 = Merge.addStatement(state, { ...Banks.parseCsv(CSV), check: null });
check("повторная загрузка не задваивает операции", a1.added === 8 && a2.added === 0 && state.txs.length === 8);

console.log(failed ? "\nПровалено проверок: " + failed : "\nВсе проверки пройдены.");
process.exit(failed ? 1 : 0);
