// Тест разбора выписки БПС-Сбербанка («Сбер Банк») на ВЫДУМАННЫХ данных.
// Запуск из папки src:  node tests/test_sber.js

const SB = require("../sber.js");
const Banks = require("../banks.js");
const Cat = require("../categories.js");

let failed = 0;
const check = (name, ok) => { if (!ok) failed++; console.log((ok ? "OK    " : "FAIL  ") + name); };
const it = (vx, vy, text) => ({ vx, vy, text });

// Операция: первая строка с датами и суммами, ниже время и описание (строки стоят ниже, как в настоящем файле)
const op = (y, post, txd, amt, lines, time = "12:00:00", cur = "BYN", amtOp = amt) => [
  it(24, y, post), it(84, y, txd), it(550, y, cur), it(620, y, amtOp), it(724, y, amt),
  it(24, y + 13, "00:00:00"), it(84, y + 13, time),
  ...lines.map((t, i) => it(264, y + i * 12.5, t)),
];
const page1 = [
  it(20, 31, 'ОАО "Сбер Банк"'), it(20, 93, "Выписка по счету за период 01.07.2026 - 31.07.2026"),
  it(20, 149, "Валюта счета BYN"),
  it(20, 206, "Входящий остаток в валюте счета"), it(230, 206, "-100.00"),
  it(24, 246, "Дата"), it(264, 246, "Наименование операции"),
  ...op(306, "06.07.2026", "06.07.2026", "-5.99", ["Абонентская плата за пакетное обслуживание -", "Абонентская плата за пользование ПУ"], "00:00:00"),
  ...op(365, "07.07.2026", "07.07.2026", "300.00", ["Зачисление других сумм - Зачисление выплат по списку"], "00:00:00"),
  ...op(424, "09.07.2026", "07.07.2026", "-22.50", ["Списание с карточного счета по карточке - Транзакция", "(дебетовая)", "BLR MINSK", 'SHOP "TEST"'], "17:36:25"),
  ...op(520, "10.07.2026", "09.07.2026", "-50.00", ["Р2Р - Перевод с карты на карту (дебет) - Транзакция", "(дебетовая)", "BLR Minsk", "P2P SOU Sber Bank"], "21:04:44"),
  ...op(620, "10.07.2026", "09.07.2026", "50.00", ["Пополнение карточного счета по карточке - Транзакция", "(кредитовая)", "BLR Minsk", "P2P SOU Sber Bank"], "20:59:00"),
  ...op(700, "30.07.2026", "30.07.2026", "0.00", ["Капитализация - Капитализация процентов"], "00:00:00"),
  ...op(760, "31.07.2026", "31.07.2026", "-1.66", ["Погашение процентов по договору овердрафта - БПСБ.", "Погашение процентов по договору овердрафта (депозит)"], "00:00:00"),
];
// Подвал на второй странице: не должен попасть в описание последней операции
const page2 = [
  it(24, 30, "Дата"), it(264, 30, "Наименование операции"),
  it(20, 100, "Исходящий остаток в валюте счета"), it(230, 100, "169.85"),
  it(20, 124, "Обороты за период в валюте счета:"), it(23, 138, "(+) поступило 350.00"), it(23, 152, "(-) списано 80.15"),
];
const pages = [page1, page2];

check("банк определяется как БПС-Сбербанк", Banks.detect(pages) && Banks.detect(pages).id === "sber");
check("чужая выписка не принимается", !SB.detect([[it(1, 1, "Транзакции по счету")]]));

const { header, txs } = SB.parse(pages);
check("период и итоги из шапки", header.from === "2026-07-01" && header.to === "2026-07-31" && header.opening === -100 && header.closing === 169.85 && header.income === 350 && header.expense === 80.15);
check("операции: 6, нулевая капитализация пропущена", txs.length === 6 && header.zeroSkipped === 1);
check("знак и сумма берутся из выписки", txs[1].amount === 300 && txs[0].amount === -5.99);
check("дата транзакции, а не отражения", txs[2].date === "2026-07-07" && txs[2].regDate === "2026-07-09");
check("время операции", txs[2].time === "17:36:25" && txs[0].time === null);
check("описание: тип, город, магазин; слово (дебетовая) убрано", /Списание с карточного счета/.test(txs[2].details) && /SHOP "TEST"/.test(txs[2].details) && !/дебетовая/.test(txs[2].details));
check("подвал не попал в описание последней операции", !/остаток|поступило/i.test(txs[5].details));
check("номер договора и счёт в разбор не попадают", !/BY\d\d|договора:/.test(JSON.stringify(txs).replace(/по договору овердрафта/g, "")));

const v = SB.validate(txs, header);
check("сверка: поступило и списано сходятся до копейки", v.incomeOk === true && v.expenseOk === true);
check("сверка: остаток сходится", v.balanceOk === true && v.ok === true);
check("сверка ловит расхождение", SB.validate(txs.slice(1), header).ok === false);

const bank = Banks.detect(pages);
const full = Banks.parse(pages);
check("P2P туда-обратно найдено как пара", full.header.pairs === 1 && full.txs.filter(t => t.pair).length === 2);
check("плата за пакет услуг: комиссии банка", Cat.categorize(txs[0]) === Cat.FEES);
check("проценты по овердрафту: комиссии банка", Cat.categorize(txs[5]) === Cat.FEES);
check("зачисление: пополнение", Cat.categorize(txs[1]) === Cat.INCOME);

console.log(failed ? `\nПровалено: ${failed}` : "\nВсе проверки пройдены.");
process.exit(failed ? 1 : 0);
